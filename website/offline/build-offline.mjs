/**
 * Offline (PWA) assets generator.
 *
 * Runs after `astro build` (see astro.config.mjs) and writes into dist/:
 *   - sw.js                  service worker that precaches the whole site
 *   - manifest.webmanifest   web app manifest (installable on the phone)
 *   - icon-192.png / icon-512.png
 *
 * No extra npm dependencies: everything here is node's stdlib + zlib.
 */
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import crypto from 'node:crypto';

const SW_FILE = 'sw.js';

/* ------------------------------------------------------------------ files */

function walk(dir, root = dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(full, root, out);
    } else if (entry.isFile()) {
      out.push(path.relative(root, full).split(path.sep).join('/'));
    }
  }
  return out;
}

/** `kino/bezdelnyk/index.html` -> `/songs/kino/bezdelnyk/` */
function toPublicUrl(base, relativePath) {
  if (relativePath.endsWith('index.html')) {
    return base + relativePath.slice(0, -'index.html'.length);
  }
  return base + relativePath;
}

/* -------------------------------------------------------------------- png */

const CRC_TABLE = (() => {
  const table = new Int32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    table[n] = c;
  }
  return table;
})();

function crc32(buf) {
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i++) c = CRC_TABLE[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function pngChunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length, 0);
  const body = Buffer.concat([Buffer.from(type, 'latin1'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body), 0);
  return Buffer.concat([len, body, crc]);
}

export function encodePng(width, height, rgba) {
  const stride = width * 4;
  const raw = Buffer.alloc((stride + 1) * height);
  for (let y = 0; y < height; y++) {
    raw[y * (stride + 1)] = 0; // filter: none
    rgba.copy(raw, y * (stride + 1) + 1, y * stride, (y + 1) * stride);
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 6; // RGBA
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    pngChunk('IHDR', ihdr),
    pngChunk('IDAT', zlib.deflateSync(raw, { level: 9 })),
    pngChunk('IEND', Buffer.alloc(0)),
  ]);
}

/* ------------------------------------------------------------------- icon */

const BG = [0x1d, 0x20, 0x21];
const BODY = [0xfe, 0x80, 0x19];
const NECK = [0xfa, 0xbd, 0x2f];

/** A simple guitar glyph: warm body with a sound hole and a fretboard. */
export function renderIcon(size) {
  const rgba = Buffer.alloc(size * size * 4);

  const inCircle = (x, y, cx, cy, r) => (x - cx) ** 2 + (y - cy) ** 2 <= r * r;
  const inRect = (x, y, x0, y0, x1, y1) => x >= x0 && x <= x1 && y >= y0 && y <= y1;

  // Colours are picked by shape; sampling 3x3 per pixel gives soft edges.
  const sample = (x, y) => {
    const body = inCircle(x, y, 0.5, 0.62, 0.27);
    const hole = inCircle(x, y, 0.5, 0.62, 0.115);
    const neck = inRect(x, y, 0.455, 0.2, 0.545, 0.42);
    const head = inRect(x, y, 0.43, 0.1, 0.57, 0.2);
    if (body && hole) return BG;
    if (body) return BODY;
    if (neck || head) return NECK;
    return BG;
  };

  const steps = 3;
  for (let py = 0; py < size; py++) {
    for (let px = 0; px < size; px++) {
      let r = 0;
      let g = 0;
      let b = 0;
      for (let sy = 0; sy < steps; sy++) {
        for (let sx = 0; sx < steps; sx++) {
          const [cr, cg, cb] = sample((px + (sx + 0.5) / steps) / size, (py + (sy + 0.5) / steps) / size);
          r += cr;
          g += cg;
          b += cb;
        }
      }
      const total = steps * steps;
      const i = (py * size + px) * 4;
      rgba[i] = Math.round(r / total);
      rgba[i + 1] = Math.round(g / total);
      rgba[i + 2] = Math.round(b / total);
      rgba[i + 3] = 255;
    }
  }

  return encodePng(size, size, rgba);
}

/* ------------------------------------------------------------------- sw.js */

function serviceWorkerSource({ base, cacheName, urls }) {
  return `'use strict';
/* Generated by offline/build-offline.mjs — do not edit dist/sw.js by hand. */
const CACHE = ${JSON.stringify(cacheName)};
const BASE = ${JSON.stringify(base)};
const PRECACHE = ${JSON.stringify(urls)};

const OFFLINE_HTML = [
  '<!DOCTYPE html><html lang="ru"><head><meta charset="utf-8">',
  '<meta name="viewport" content="width=device-width,initial-scale=1">',
  '<title>Нет сети</title></head>',
  '<body style="margin:0;min-height:100vh;display:flex;align-items:center;justify-content:center;',
  'text-align:center;padding:24px;background:#1D2021;color:#EBDBB2;',
  'font-family:system-ui,-apple-system,sans-serif">',
  '<div><h1 style="font-size:1.3rem">Страница ещё не сохранена</h1>',
  '<p style="color:#928374">Откройте её один раз с интернетом — дальше она будет доступна офлайн.</p>',
  '<p><a style="color:#FE8019" href="' + BASE + '">К списку песен</a></p></div>',
  '</body></html>',
].join('');

self.addEventListener('install', (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE);
      await Promise.all(
        PRECACHE.map((url) =>
          cache.add(new Request(url, { cache: 'reload' })).catch(() => null)
        )
      );
      await self.skipWaiting();
    })()
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key)));
      await self.clients.claim();
    })()
  );
});

function isCacheable(request, url) {
  if (request.method !== 'GET') return false;
  if (url.origin !== self.location.origin) return false;
  return url.pathname.indexOf(BASE) === 0;
}

async function cacheFirst(request) {
  const cache = await caches.open(CACHE);
  const hit = await cache.match(request, { ignoreSearch: true });
  if (hit) return hit;
  const response = await fetch(request);
  if (response && response.ok) {
    const copy = response.clone();
    cache.put(request, copy).catch(() => null);
  }
  return response;
}

async function handleNavigation(request) {
  const cache = await caches.open(CACHE);
  const url = new URL(request.url);
  const withoutSlash = url.pathname.endsWith('/') ? url.pathname.slice(0, -1) : url.pathname;

  const variants = [url.pathname, withoutSlash, withoutSlash + '/', withoutSlash + '/index.html'];
  for (const variant of variants) {
    const hit = await cache.match(new Request(self.location.origin + variant), { ignoreSearch: true });
    if (hit) return hit;
  }

  try {
    const response = await fetch(request);
    if (response && response.ok) {
      const copy = response.clone();
      cache.put(request, copy).catch(() => null);
    }
    return response;
  } catch (error) {
    return new Response(OFFLINE_HTML, {
      status: 200,
      headers: { 'Content-Type': 'text/html; charset=utf-8' },
    });
  }
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (!isCacheable(request, url)) return;

  if (request.mode === 'navigate') {
    event.respondWith(handleNavigation(request));
    return;
  }

  event.respondWith(cacheFirst(request).catch(() => new Response('', { status: 504 })));
});
`;
}

/* --------------------------------------------------------------- generate */

export function generateOfflineAssets({ distDir, base }) {
  const files = walk(distDir).filter((file) => file !== SW_FILE && !file.endsWith('.map'));

  const hasher = crypto.createHash('sha1');
  for (const file of files.slice().sort()) {
    hasher.update(file);
    hasher.update(fs.readFileSync(path.join(distDir, file)));
  }
  const build = hasher.digest('hex').slice(0, 8);
  const cacheName = `songbook-${build}`;

  const urls = files.map((file) => toPublicUrl(base, file)).sort();

  fs.writeFileSync(path.join(distDir, SW_FILE), serviceWorkerSource({ base, cacheName, urls }));
  fs.writeFileSync(
    path.join(distDir, 'manifest.webmanifest'),
    JSON.stringify(
      {
        name: 'Песенник — аккорды',
        short_name: 'Песенник',
        description: 'Песенник с аккордами, транспонером и автоскроллом. Работает без интернета.',
        lang: 'ru',
        start_url: base,
        scope: base,
        display: 'standalone',
        background_color: '#1D2021',
        theme_color: '#1D2021',
        icons: [
          { src: `${base}icon-192.png`, sizes: '192x192', type: 'image/png', purpose: 'any' },
          { src: `${base}icon-512.png`, sizes: '512x512', type: 'image/png', purpose: 'any maskable' },
        ],
      },
      null,
      2
    ) + '\n'
  );
  fs.writeFileSync(path.join(distDir, 'icon-192.png'), renderIcon(192));
  fs.writeFileSync(path.join(distDir, 'icon-512.png'), renderIcon(512));

  return { cacheName, build, fileCount: urls.length };
}
